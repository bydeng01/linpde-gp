"""
Emit the LaTeX metrics table (the replacement for the old figure panel ``h``)
for the 2D Poisson *partial-BC* combination showcase.

The numbers are read from ``diagnostics.json`` (written by ``run.py``), so the
table is guaranteed to match ``figure_poisson_2d_partialBC`` and never drifts
from the figure. Run:

    python make_table.py [out_dir]

writes ``table_metrics.tex`` next to ``diagnostics.json``. ``\\input`` it from
the paper; it needs ``\\usepackage{booktabs}``.
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# Placeholders (@TOKEN@) are used instead of str.format/%-substitution so that
# the literal LaTeX braces, $ math, and \% in the template are left untouched.
TEMPLATE = r"""% Auto-generated by make_table.py from diagnostics.json -- do not edit by hand.
% Requires \usepackage{booktabs}.
\begin{table}[tbp]
\centering
\setlength{\tabcolsep}{4pt}
{\small
\begin{tabular}{lccc}
\toprule
 & equality only & $+$\,inequality & reduction \\
 & $u\mid E$ & $u\mid(E,C)$ & \\
\midrule
RMSE                        & @L2U@ & @L2C@ & $@L2R@\%$ \\
Max error                   & @MXU@ & @MXC@ & $@MXR@\%$ \\
Mean $1.96\sigma$ band width & @BU@ & @BC@ & $@BR@\%$ \\
Free-corner $(1,1)$ error   & @FCU@ & @FCC@ & $@FCR@\%$ \\
\bottomrule
\end{tabular}
}
\caption{Accuracy and uncertainty on the 2D Poisson problem with
\emph{partial} boundary data (Dirichlet $u=0$ only on $x{=}0,\,y{=}0$; the $(1,1)$
corner is left free). Adding the monotonicity inequalities
$\partial_x u,\,\partial_y u\ge 0$ to the under-determined PDE-equality
posterior lowers every error and uncertainty metric. Lower is better; the
last column is the relative reduction. The prior-predictive
constraint-satisfaction probability is $P(C\mid E)=@PCE@$.}
\label{tab:poisson2d_partialBC}
\end{table}
"""


def _reduction(unc: float, con: float) -> int:
    """Signed integer percent reduction, matching the figure's ``:.0f`` rule."""
    return -int(round(100.0 * (1.0 - con / unc)))


def main(out_dir: str | None = None) -> None:
    out_dir = out_dir or HERE
    with open(os.path.join(out_dir, "diagnostics.json")) as fh:
        d = json.load(fh)

    repl = {
        "@PCE@": f"{d['p_ce']:.2f}",
        "@L2U@": f"{d['l2_unc']:.3f}",
        "@L2C@": f"{d['l2_con']:.3f}",
        "@L2R@": f"{_reduction(d['l2_unc'], d['l2_con']):d}",
        "@MXU@": f"{d['max_abs_unc']:.3f}",
        "@MXC@": f"{d['max_abs_con']:.3f}",
        "@MXR@": f"{_reduction(d['max_abs_unc'], d['max_abs_con']):d}",
        "@BU@": f"{d['band_unc']:.3f}",
        "@BC@": f"{d['band_con']:.3f}",
        "@BR@": f"{_reduction(d['band_unc'], d['band_con']):d}",
        "@FCU@": f"{d['free_corner_unc']:.3f}",
        "@FCC@": f"{d['free_corner_con']:.3f}",
        "@FCR@": f"{_reduction(d['free_corner_unc'], d['free_corner_con']):d}",
    }
    tex = TEMPLATE
    for token, value in repl.items():
        tex = tex.replace(token, value)

    path = os.path.join(out_dir, "table_metrics.tex")
    with open(path, "w") as fh:
        fh.write(tex)
    print(f"wrote {path}\n")
    print(tex)


if __name__ == "__main__":
    main(out_dir=sys.argv[1] if len(sys.argv) > 1 else None)
